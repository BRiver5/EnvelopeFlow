// Категориальная палитра для доната "расходы по конвертам" — конвертов может
// быть больше, чем у типичного приложения категорий (8-12), поэтому набор
// шире обычного. Оттенки специально держатся на расстоянии и от акцента
// (#849325, hue~68°), и друг от друга, чтобы донат не превращался в градиент
// "всё зелёное".
export const ENVELOPE_PALETTE: string[] = [
  "#3B6FB0", // синий
  "#B0563B", // терракотовый
  "#5B4E9E", // фиолетовый
  "#3B9E82", // тёмная бирюза
  "#B04B86", // малиновый
  "#9E8B3B", // горчичный
  "#3B8FB0", // сине-голубой
  "#8C3B4F", // бордовый
  "#5E9E3B", // травяной
  "#6B5B9E", // лавандовый
];

export function colorForIndex(index: number): string {
  return ENVELOPE_PALETTE[index % ENVELOPE_PALETTE.length];
}
